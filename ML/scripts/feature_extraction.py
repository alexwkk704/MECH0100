"""
feature_extraction.py  -  generic STL -> geometric-features extractor
=====================================================================
Extracts ML-ready geometric features from every STL in a folder.
Works for ANY lattice STL dataset (ADMS, TPMS, ...).

USERS DO NOT EDIT THIS FILE.
All settings live in ML_settings.xlsx (created automatically on first
run, next to this script). Open it in Excel, edit the values, save,
run again - same workflow as runs_input.xlsx for the simulations.

Design rules (Alex / MECH0100, 18-07-2026):
  * Label-free: STLs in -> features CSV out. FEA labels joined separately.
  * All shape features DIMENSIONLESS (scaled by cell size) so datasets
    with different cell sizes (ADMS 3 mm vs TPMS 10 mm) are comparable.
  * Deterministic (fixed seed), resume-safe (skips files already done).
  * No fragile deps: curvature computed from first principles
    (angle defect / dihedral angles), thickness via opposite-normal
    KD-tree search (cannot shoot through pores). Only numpy/scipy/trimesh-load.
  * Self-validating: thickness_ratio column ~= 1.0 proves the features
    describe the geometry we think they do.

Run:  double-click RUN_FEATURES.bat
"""

