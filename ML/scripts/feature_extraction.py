def main():
    S = load_settings()

    # ---- CLI overrides -------------------------------------------------------
    # The workbook holds the ADMS defaults. A partner dataset (Zhezhe's TPMS) needs
    # a different folder, cell size and thickness convention - but editing the
    # workbook to run it, then editing it back, is exactly how two datasets end up
    # extracted with different settings and nobody notices. Overriding on the
    # command line keeps ONE canonical workbook and makes each run self-describing.
    #   --stl-folder --output-csv --dataset-tag --cell-size --thickness-convention
    def _arg(flag, cast=str):
        if flag in sys.argv:
            i = sys.argv.index(flag)
            if len(sys.argv) > i + 1:
                return cast(sys.argv[i + 1])
        return None
    _ov = {"stl_folder": _arg("--stl-folder"),
           "output_csv": _arg("--output-csv"),
           "dataset_tag": _arg("--dataset-tag"),
           "cell_size_mm": _arg("--cell-size", float),
           "thickness_convention": _arg("--thickness-convention"),
           "max_file_mb": _arg("--max-file-mb", float)}
    applied = []
    for k, v in _ov.items():
        if v is None:
            continue
        if k == "stl_folder":
            v = os.path.normpath(v if os.path.isabs(v) else os.path.join(BASE_DIR, v))
        elif k == "output_csv":
            v = run_paths.data_path(v)
        elif k == "thickness_convention":
            v = str(v).strip().lower()
        applied.append(f"{k}={v}")
        S[k] = v
    if applied:
        print("[override] " + "   ".join(applied))

    test_n = None
    if "--test" in sys.argv:
        i = sys.argv.index("--test")
        test_n = int(sys.argv[i + 1]) if len(sys.argv) > i + 1 else 3

    stl_dir, out_csv = str(S["stl_folder"]), str(S["output_csv"])
    # Recursive: ADMS STLs sit flat in one folder, the partner's TPMS STLs sit in
    # one subfolder per topology. The immediate parent folder name becomes the
    # `topology` column (empty for a flat layout, so ADMS behaviour is unchanged).
    files = []
    for _root, _dirs, _fs in os.walk(stl_dir):
        for _f in _fs:
            if _f.lower().endswith(".stl"):
                files.append(os.path.relpath(os.path.join(_root, _f), stl_dir))
    files = sorted(files)
    if not files:
        print(f"[!] no STL files in {stl_dir}"); return
    _nsub = sum(1 for r in files if os.path.dirname(r))
    if _nsub:
        print(f"[ok] {len(files)} STLs, {_nsub} inside topology subfolders")

    done = set()
    if os.path.exists(out_csv):
        with open(out_csv, newline="", encoding="utf-8") as f:
            done = {(str(r.get("topology", "")), r["file"]) for r in csv.DictReader(f)
                    if not str(r.get("status", "")).startswith(("ERROR", "SKIP"))}
    # Refuse to append under a stale header. FIELDS gained `topology`; appending
    # new-order rows beneath an old header shifts every column silently.
    if os.path.exists(out_csv):
        with open(out_csv, newline="", encoding="utf-8") as _f:
            _hdr = next(csv.reader(_f), [])
        if _hdr and _hdr != FIELDS:
            sys.exit(f"[E] {out_csv} was written with a DIFFERENT column set.\n"
                     f"    on disk : {len(_hdr)} cols, starts {_hdr[:4]}\n"
                     f"    expected: {len(FIELDS)} cols, starts {FIELDS[:4]}\n"
                     f"    Appending would shift every column. Delete or rename that file "
                     f"and re-extract from scratch.")
    write_header = not os.path.exists(out_csv)
    out = open(out_csv, "a", newline="", encoding="utf-8")
    w = csv.DictWriter(out, fieldnames=FIELDS)
    if write_header:
        w.writeheader()

    todo = [r for r in files if (_topo_of(r), os.path.basename(r)) not in done]
    if test_n: todo = todo[:test_n]
    print(f"feature_extraction | dataset={S['dataset_tag']} cell={S['cell_size_mm']}mm "
          f"conv={S['thickness_convention']} seed={S['random_seed']}")
    print(f"{len(files)} STLs, {len(done)} done, {len(todo)} to process"
          + (f"  (TEST MODE {test_n})" if test_n else ""))

    for i, rel in enumerate(todo, 1):
        path = os.path.join(stl_dir, rel)
        f = os.path.basename(rel)
        topo = _topo_of(rel)
        mb = os.path.getsize(path) / 1e6
        if mb > S["max_file_mb"]:
            row = dict.fromkeys(FIELDS, "")
            row.update({"dataset": S["dataset_tag"], "file": f, "topology": topo,
                        "status": f"SKIPPED >{S['max_file_mb']}MB"})
            w.writerow(row); out.flush()
            print(f"[{i}/{len(todo)}] {f}  SKIPPED (>{S['max_file_mb']} MB)")
            continue
        try:
            row = extract_one(path, f[:-4], S)
            row["topology"] = topo
            w.writerow(row); out.flush()
            print(f"[{i}/{len(todo)}] {f}  VF={row['VF']}  "
                  f"t_med={row['thickness_med_mm']}  ratio={row['thickness_ratio']}  "
                  f"({row['extract_s']}s)")
        except Exception as e:
            row = dict.fromkeys(FIELDS, "")
            row.update({"dataset": S["dataset_tag"], "file": f, "topology": topo,
                        "status": f"ERROR {e}"})
            w.writerow(row); out.flush()
            print(f"[{i}/{len(todo)}] {f}  ERROR: {e}")

    out.close()
    print("\ndone. output:", out_csv)
    print("CHECK: thickness_ratio ~1.0 on every row = feature-accuracy validation.")


if __name__ == "__main__":
    main()
