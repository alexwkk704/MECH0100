# filename parameter parsing (best effort, generic)
# ------------------------------------------------------------------
def parse_params(stem, S=None):
    """Pull design parameters out of the filename using USER-SUPPLIED regexes.

    The five slots (inner, density, t, seed, multi) are generic - map whatever
    your filenames encode onto them via the 'filename_params' setting. Nothing
    about the ADMS naming scheme is assumed here.

    Format:   slot:regex ; slot:regex ; ...
    A regex with TWO capture groups is read as  group1.group2  (so the common
    "22p85" -> 22.85 convention works); ONE group is taken literally.

    ADMS default:  inner:i(\\d+)p(\\d+); density:d(\\d+)p(\\d+); t:t(\\d+)p(\\d+);
                   seed:_s(\\d+); multi:m(\\d+)p(\\d+)
    A TPMS user might instead write:
                   density:vf([0-9.]+); t:th([0-9.]+); seed:seed(\\d+)

    Slots left unmatched come out blank - that is not an error, it only means
    those columns are empty for this dataset.
    """
    p = {"inner": "", "density": "", "t": "", "seed": "", "multi": ""}
    spec = (S or {}).get("filename_params", "") if S else ""
    if not str(spec).strip():
        spec = DEFAULT_FILENAME_PARAMS
    for part in str(spec).split(";"):
        if ":" not in part:
            continue
        slot, rx = part.split(":", 1)
        slot, rx = slot.strip(), rx.strip()
        if slot not in p or not rx:
            continue
        try:
            m = re.search(rx, stem)
        except re.error:
            continue
        if not m:
            continue
        g = [x for x in m.groups() if x is not None]
        p[slot] = f"{g[0]}.{g[1]}" if len(g) >= 2 else (g[0] if g else "")
    return p


